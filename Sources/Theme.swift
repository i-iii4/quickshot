import AppKit

/// Токены оформления QuickShot. Карточки и хаб используют собственную тёмную
/// Vercel/Geist-подобную command surface; системный Liquid Glass остаётся только там,
/// где это явно выбрано для отдельного нативного окна.
enum QS {
    /// Радиус скругления карточки-скриншота (единственный кастомный радиус в приложении).
    static let radiusCard: CGFloat = 8
    /// Стандартный шаг разметки macOS (8pt-сетка) — отступ и зазор контролов.
    static let s2: CGFloat = 8
}
